/*函数功能：在指定区域内填充指定颜色
区域大小:
	(xend-xsta)*(yend-ysta)
color: 使用的颜色
---------------------------------------------------------------*/
void ILI9341_fill(uint16_t xsta,uint16_t ysta,uint16_t xend,uint16_t yend,uint16_t color)
{          
	uint16_t i,j; 
	
	ILI9341_address_set(xsta,ysta,xend,yend);      //设置光标位置 
	
	for(i=ysta;i<=yend;i++)
	{													   	 	
		for(j=xsta;j<=xend;j++)ILI9341_wr_data(color);//设置光标位置 	    
	}
}  
